package com.example.cognisync.model;

public class TimetableItem {

    private int day;
    private String title;
    private String module;
    private int duration;

    public int getDay() {
        return day;
    }

    public String getTitle() {
        return title;
    }

    public String getModule() {
        return module;
    }

    public int getDuration() {
        return duration;
    }
}
